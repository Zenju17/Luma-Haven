#!/usr/bin/env python3
"""Regenerate docs/ERD.md (Mermaid) and docs/API.md from the code. No database connection is needed.

    DATABASE_URL=postgresql://x:x@127.0.0.1:1/x .venv/bin/python scripts/generate_docs.py
"""
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'backend'))
os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'config.settings')
import django  # noqa: E402

django.setup()
from django.apps import apps  # noqa: E402
from django.urls import get_resolver  # noqa: E402


def erd():
    lines = ['# Entity-relationship diagram', '', '_Generated by `scripts/generate_docs.py` from `backend/core/models.py`. Do not edit by hand._', '',
             '```mermaid', 'erDiagram']
    rels = []
    for model in sorted(apps.get_app_config('core').get_models(), key=lambda m: m.__name__):
        lines.append(f'  {model.__name__} {{')
        for f in model._meta.concrete_fields:
            kind = f.get_internal_type()
            tag = ' PK' if f.primary_key else (' FK' if f.is_relation else '')
            lines.append(f'    {kind} {f.name}{tag}')
            if f.is_relation and f.related_model:
                left = '|o' if f.null else '||'
                right = 'o|' if f.one_to_one else 'o{'
                rels.append(f'  {f.related_model.__name__} {left}--{right} {model.__name__} : "{f.name}"')
        lines.append('  }')
    lines += sorted(set(rels)) + ['```', '']
    return '\n'.join(lines)


def api():
    rows = []

    def walk(patterns, prefix=''):
        for p in patterns:
            if hasattr(p, 'url_patterns'):
                walk(p.url_patterns, prefix + str(p.pattern))
            else:
                path = '/' + prefix + str(p.pattern)
                cls = getattr(p.callback, 'cls', None)
                methods = ', '.join(sorted(m.upper() for m in getattr(cls, 'http_method_names', []) if m not in ('options', 'head') and hasattr(cls, m))) if cls else 'GET'
                rows.append((path, methods or 'GET', getattr(cls, '__name__', getattr(p.callback, '__name__', ''))))

    walk(get_resolver().url_patterns)
    out = ['# API endpoint index', '', '_Generated by `scripts/generate_docs.py`. The live OpenAPI schema is at `/api/schema/` (Swagger UI: `/api/docs/`). '
           'Authorization is enforced server-side per view; see [PERMISSIONS.md](PERMISSIONS.md)._', '',
           '| Path | Methods | View |', '|---|---|---|']
    for path, methods, name in sorted(r for r in rows if r[0].startswith('/api/v1/')):
        out.append(f'| `{path.replace("<", "&lt;").replace(">", "&gt;")}` | {methods} | `{name}` |')
    return '\n'.join(out) + '\n'


(ROOT / 'docs' / 'ERD.md').write_text(erd())
(ROOT / 'docs' / 'API.md').write_text(api())
print('wrote docs/ERD.md and docs/API.md')
